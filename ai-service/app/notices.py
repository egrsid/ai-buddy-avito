"""Служебные пометки сервиса в тексте ответа.

Их дописывает failover.py (резерв, offline, обрыв) и mock-режим. Фронтенд v2 по ним
отличает ответ модели от fallback. Из истории чата пометки вырезаются до отправки модели
(prompt.py): иначе модель копирует «Произошла ошибка обращения к LLM…» в свои ответы,
и чат после одного сбоя навсегда выглядит как fallback.
"""

NOTICE = (
    "Произошла ошибка обращения к LLM. Работает fallback. "
    "Обратись к своему наставнику напрямую для решения вопроса. "
)
RESERVE_NOTICE = "Используется резервная модель.\n\n"
INTERRUPTED = "\n\n_Ответ модели прервался. Повтори вопрос или обратись к наставнику._"
OFFLINE_NOTICE = (
    "Ответ ниже подготовлен без LLM по разрешённому контексту и шаблонам. "
    "Он не подтверждает выполнение шага.\n\n"
)
# Начало шаблонного ответа mock-режима: здесь о режиме уже сказано в OFFLINE_NOTICE.
MOCK_PREFIX = "Демо-режим mock: ответ подготовлен без LLM.\n\n"

SERVICE_NOTES = (NOTICE, RESERVE_NOTICE, OFFLINE_NOTICE, INTERRUPTED, MOCK_PREFIX)


def strip_service_notes(text: str) -> str:
    """Текст ответа без служебных пометок сервиса (пробелы по краям тоже убираем)."""
    for note in SERVICE_NOTES:
        text = text.replace(note.strip(), "")
    return text.strip()
